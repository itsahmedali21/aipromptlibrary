export function getPromptBySlug(slug: string) {
  return prompts.find((p) => p.slug === slug);
}

export function getPromptsByCategory(slug: string) {
  return prompts.filter((p) => p.category === slug);
}

export function getFeaturedPrompts() {
  return prompts.filter((p) => p.featured);
}

export function getRelatedPrompts(prompt: Prompt, limit = 3) {
  return prompts
    .filter((p) => p.id !== prompt.id && p.category === prompt.category)
    .sort((a2, b) => b.popularity - a2.popularity)
    .slice(0, limit);
}

export function sortPrompts(list: Prompt[], sort: string) {
  const copy = [...list];
  switch (sort) {
    case "newest":
      return copy.sort((a2, b) => +new Date(b.createdAt) - +new Date(a2.createdAt));
    case "most-copied":
      return copy.sort((a2, b) => b.usageCount - a2.usageCount);
    case "trending":
      return copy.sort((a2, b) => b.popularity - a2.popularity || +new Date(b.createdAt) - +new Date(a2.createdAt));
    case "popular":
    default:
      return copy.sort((a2, b) => b.popularity - a2.popularity);
  }
}
